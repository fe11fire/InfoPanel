// Package PDF.js as a classic script for the panel's file:// entry point.
const fs = require('node:fs');
const path = require('node:path');
const { createRequire } = require('node:module');

const root = path.join(__dirname, '..');
const requireBuild = createRequire(path.join(process.argv[2] || root, 'package.json'));
const esbuild = requireBuild('esbuild');
const dist = path.dirname(requireBuild.resolve('pdfjs-dist/package.json'));
const output = path.join(root, 'assets/pdfjs');
const legacy = path.join(dist, 'legacy/build');
const worker = esbuild.transformSync(fs.readFileSync(path.join(legacy, 'pdf.worker.min.mjs'), 'utf8'), {
    format: 'iife', target: 'es2022', minify: true,
    define: { 'import.meta.url': 'self.location.href' }
}).code;
const assetFolders = { cMapUrl: 'cmaps', standardFontDataUrl: 'standard_fonts', wasmUrl: 'wasm' };
const assets = {};
const notices = [];
for (const [kind, folder] of Object.entries(assetFolders)) {
    assets[kind] = {};
    for (const name of fs.readdirSync(path.join(dist, folder)).sort()) {
        const file = path.join(dist, folder, name);
        if (name.startsWith('LICENSE')) {
            notices.push(folder + '/' + name + '\n\n' + fs.readFileSync(file, 'utf8').trim());
        } else {
            assets[kind][name] = fs.readFileSync(file).toString('base64');
        }
    }
}

const source = `
import { getDocument, PDFWorker } from ${JSON.stringify(path.join(legacy, 'pdf.min.mjs'))};
const workerSource = ${JSON.stringify(worker)};
const assets = ${JSON.stringify(assets)};

class LocalPdfAssets {
    async fetch({ kind, filename }) {
        const encoded = assets[kind]?.[filename];
        if (typeof encoded !== 'string') throw new Error('Unknown PDF.js asset: ' + filename);
        return Uint8Array.from(atob(encoded), char => char.charCodeAt(0));
    }
}

export function open(data) {
    const url = URL.createObjectURL(new Blob([workerSource], { type: 'text/javascript' }));
    let port, worker;
    try {
        port = new Worker(url);
        worker = PDFWorker.create({ port });
        const task = getDocument({
            data, worker, useWorkerFetch: false, BinaryDataFactory: LocalPdfAssets,
            cMapUrl: './cmaps/', standardFontDataUrl: './standard_fonts/', wasmUrl: './wasm/',
            useSystemFonts: false, maxImageSize: 24000000, canvasMaxAreaInBytes: 96000000
        });
        return {
            promise: Promise.race([task.promise, new Promise((resolve, reject) => {
                port.addEventListener('error', event => reject(new Error('Не удалось запустить обработчик PDF.js' +
                    (event.message ? ': ' + event.message : ''))), { once: true });
            })]),
            async destroy() {
                let timeout;
                try {
                    await Promise.race([task.destroy(), new Promise(resolve => {
                        timeout = setTimeout(resolve, 1000);
                    })]);
                } catch {
                    // Worker termination below also covers failed document setup.
                } finally {
                    clearTimeout(timeout);
                    worker.destroy();
                    port.terminate();
                    URL.revokeObjectURL(url);
                }
            }
        };
    } catch (error) {
        worker?.destroy();
        port?.terminate();
        URL.revokeObjectURL(url);
        throw error;
    }
}
`;

const build = esbuild.buildSync({
    stdin: { contents: source, resolveDir: root },
    bundle: true, format: 'iife', globalName: 'InfoPanelPdf',
    target: 'es2022', minify: true, legalComments: 'eof',
    define: { 'import.meta.url': 'undefined' },
    write: false
});
fs.mkdirSync(output, { recursive: true });
fs.writeFileSync(path.join(output, 'pdf-engine.js'),
    '// Generated by npm run build:pdf. See THIRD-PARTY-NOTICES.txt.\n' + build.outputFiles[0].text);
fs.writeFileSync(path.join(output, 'THIRD-PARTY-NOTICES.txt'),
    fs.readFileSync(path.join(dist, 'LICENSE'), 'utf8').trim() + '\n\n' + notices.join('\n\n').replace(/[ \t]+$/gm, '') + '\n');
